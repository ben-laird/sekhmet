import { assertEquals } from "@std/assert";
import { checkModuleDocs, leadingDocBlock, moduleDoc } from "./module-doc.ts";
import type { Member } from "./workspace.ts";

function member(exports: Record<string, string>): Member {
	return {
		dir: "packages/a",
		manifestPath: "packages/a/deno.json",
		manifestText: "{}",
		manifest: {
			name: "@sekhmet/a",
			publish: true,
			publishExclude: [],
			exports,
			workspace: [],
		},
	};
}

Deno.test("leadingDocBlock reads the doc block after line comments, before code", () => {
	// Given: a generated header then a doc block, a doc block after code, and
	// a plain block comment
	const generated =
		"// GENERATED by scripts/gen-main\n\n/**\n * Main.\n */\nexport {};";
	const afterCode = "export {};\n/** Late. */";
	const plain = "/* Not a doc. */\nexport {};";

	// When: reading each one's leading doc block
	const blocks = [generated, afterCode, plain].map(leadingDocBlock);

	// Then: only the block before any code counts
	assertEquals(blocks, ["/**\n * Main.\n */", undefined, undefined]);
});

Deno.test("moduleDoc requires a @module tag at the start of a JSDoc line", () => {
	// Given: tagged blocks in multi-line and one-line form, an untagged
	// symbol doc, and a block that only mentions @module mid-line
	const tagged = "/**\n * The core.\n *\n * @module\n */\nexport {};";
	const oneLine = "/** @module */\nexport {};";
	const symbolDoc = "/** Adds. */\nexport function add() {}";
	const mention = "/** See the @module tag. */\nexport {};";

	// When: reading each one's module doc
	const docs = [tagged, oneLine, symbolDoc, mention].map(moduleDoc);

	// Then: only the tagged blocks are module docs
	assertEquals(docs, [
		"/**\n * The core.\n *\n * @module\n */",
		"/** @module */",
		undefined,
		undefined,
	]);
});

Deno.test("checkModuleDocs reports each entrypoint file without a module doc once", () => {
	// Given: a documented entrypoint, two subpaths sharing an undocumented
	// file, an entrypoint whose doc block lacks @module, and a missing file
	const files = new Map([
		["packages/a/mod.ts", "/** A. @module\n * @module\n */\nexport {};"],
		["packages/a/mini.ts", "export const m = 1;"],
		["packages/a/sym.ts", "/** Adds. */\nexport function add() {}"],
	]);
	const pkg = member({
		".": "./mod.ts",
		"./mini": "./mini.ts",
		"./mini/all": "./mini.ts",
		"./sym": "./sym.ts",
		"./gone": "./gone.ts",
	});

	// When: checking its module docs
	const findings = checkModuleDocs({ member: pkg, files });

	// Then: the two undocumented files are reported, naming their subpaths
	assertEquals(findings, [
		{
			check: "module-doc",
			file: "packages/a/mini.ts",
			line: 1,
			message:
				'entrypoint "./mini", "./mini/all" does not open with a /** … @module */ doc; JSR scores a module doc on every entrypoint',
		},
		{
			check: "module-doc",
			file: "packages/a/sym.ts",
			line: 1,
			message:
				'entrypoint "./sym" opens with a doc block that has no @module tag; JSR scores a module doc on every entrypoint',
		},
	]);
});
