/** The header that marks a file as generated. */
export const GENERATED_HEADER =
	"// GENERATED by scripts/gen-main — do not edit";

/** Why a feature's main module could not be generated. */
export interface GenerateError {
	/** Discriminant. */
	readonly kind: "generate";
	/** The feature's entrypoint. */
	readonly entrypoint: string;
	/** The mini symbol at fault, if any. */
	readonly symbol: string | undefined;
	/** What went wrong. */
	readonly message: string;
}

/** Inputs to {@linkcode generateMain}. */
export interface GenerateInput {
	/** The feature being generated. */
	readonly feature: Feature;
	/** The mini barrel's exported symbols. */
	readonly symbols: readonly DocSymbol[];
	/** Source text of every file a symbol is declared in, keyed by file URL. */
	readonly sources: ReadonlyMap<string, string>;
	/** The mini barrel's file URL. */
	readonly miniUrl: string;
	/** The generated module's file URL. */
	readonly outputUrl: string;
}

/** A generated value, or why generation failed. */
export type Generated<T> = Result<T, GenerateError>;

/** A rendered method or function: overload heads, an implementation, its docs. */
interface Member {
	readonly name: string;
	readonly source: string;
}

/** Shared state while generating one module. */
interface Module {
	readonly feature: Feature;
	readonly miniNames: ReadonlySet<string>;
	/** Mini functions that are methods of the main class. */
	readonly methodNames: ReadonlySet<string>;
	/** Mini exports left out of main. */
	readonly omitted: ReadonlySet<string>;
	readonly wrapNames: ReadonlySet<string>;
	/** Each wrap target's mapper per type argument (for nested conversion). */
	readonly mappers: ReadonlyMap<string, readonly (string | undefined)[]>;
	readonly localNames: ReadonlySet<string>;
	readonly sources: ReadonlyMap<string, string>;
	readonly outputUrl: string;
	/** Type-only imports: specifier → (imported name → local name). */
	readonly typeImports: Map<string, Map<string, string>>;
}

const EMPTY_RENAME: ReadonlyMap<string, string> = new Map();

function failure({
	feature,
	symbol,
	message,
}: {
	feature: Feature;
	symbol: string | undefined;
	message: string;
}): Generated<never> {
	return err({
		kind: "generate",
		entrypoint: feature.entrypoint,
		symbol,
		message,
	});
}

function specifierFor({ from, to }: { from: string; to: string }): string {
	const path = relative(dirname(new URL(from).pathname), new URL(to).pathname);

	return path.startsWith(".") ? path : `./${path}`;
}

function originalName(ref: NamedRef): string {
	return ref.resolution.kind === "import" ? ref.resolution.name : ref.name;
}

function importType({
	module,
	specifier,
	name,
}: {
	module: Module;
	specifier: string;
	name: string;
}): string {
	const names = module.typeImports.get(specifier) ?? new Map<string, string>();
	module.typeImports.set(specifier, names);

	const existing = names.get(name);
	if (existing !== undefined) return existing;

	const local = module.localNames.has(name) ? `Mini${name}` : name;
	names.set(name, local);

	return local;
}

/**
 * The render context for a declaration in `fileUrl`: names exported by the
 * mini barrel are spelled `mini.X`; others are imported by type.
 */
function contextFor({
	module,
	fileUrl,
	rename,
}: {
	module: Module;
	fileUrl: string;
	rename: ReadonlyMap<string, string>;
}): RenderContext {
	return {
		rename,
		reference(ref) {
			if (ref.resolution.kind === "global") return ref.name;

			const name = originalName(ref);
			if (module.miniNames.has(name)) return `mini.${name}`;

			if (ref.resolution.kind === "local") {
				const specifier = specifierFor({ from: module.outputUrl, to: fileUrl });
				return importType({ module, specifier, name });
			}

			const { specifier } = ref.resolution;
			const resolved = specifier.startsWith(".")
				? specifierFor({
						from: module.outputUrl,
						to: new URL(specifier, fileUrl).href,
					})
				: specifier;

			return importType({ module, specifier: resolved, name });
		},
	};
}

/** The wrap target a top-level type names, if it names one. */
function wrapTargetOf(
	wrapNames: ReadonlySet<string>,
	type: TypeNode | undefined,
): string | undefined {
	if (type?.kind !== "ref" || type.resolution.kind === "typeParam")
		return undefined;

	const name = originalName({ name: type.name, resolution: type.resolution });

	return wrapNames.has(name) ? name : undefined;
}

/** Renders a type, spelling a top-level wrap target as its main class. */
function renderWrapped({
	module,
	type,
	context,
}: {
	module: Module;
	type: TypeNode;
	context: RenderContext;
}): string {
	const target = wrapTargetOf(module.wrapNames, type);
	if (target === undefined || type.kind !== "ref") {
		return renderType({ type, context });
	}

	const args = type.args.map((arg) => renderType({ type: arg, context }));

	return args.length === 0 ? target : `${target}<${args.join(", ")}>`;
}

/** Whether a return type names a wrap target anywhere main converts it. */
function needsConversion({
	wrapNames,
	type,
}: {
	wrapNames: ReadonlySet<string>;
	type: TypeNode | undefined;
}): boolean {
	if (type === undefined) return false;

	const planned = convertReturn({
		type,
		context: {
			render: () => "",
			wrapTarget: (inner) => wrapTargetOf(wrapNames, inner),
			mappers: () => [],
		},
	});

	// A plan that fails (a missing mapper) still needs converting; rendering
	// the wrapper reports the failure.
	return !planned.ok || planned.value.conversion.kind !== "none";
}

function signaturesOf(symbol: DocSymbol): FunctionDeclaration[] {
	const functions = symbol.declarations.filter(
		(declaration): declaration is FunctionDeclaration =>
			declaration.kind === "function",
	);

	return functions.length > 1
		? functions.filter((declaration) => !declaration.hasBody)
		: functions;
}

function isSelfOfPrimary(primary: string, param: Param | undefined): boolean {
	if (param?.kind !== "identifier" || param.name !== "self") return false;
	const type = param.type;
	if (type?.kind !== "ref" || type.resolution.kind === "typeParam")
		return false;

	return (
		originalName({ name: type.name, resolution: type.resolution }) === primary
	);
}

/** A signature with the tuple labels `deno doc` dropped restored from source. */
function labelled(
	module: Module,
	signature: FunctionDeclaration,
): FunctionDeclaration {
	const source = module.sources.get(signature.location.filename);
	if (source === undefined) return signature;

	return withTupleLabels({
		declaration: signature,
		text: sliceFromByte({ source, byteIndex: signature.location.byteIndex }),
	});
}

function modifiersOf(
	module: Module,
	declaration: FunctionDeclaration | ClassDeclaration,
): TypeParamModifiers {
	const source = module.sources.get(declaration.location.filename);
	if (source === undefined) return new Map();

	return typeParamModifiers(
		sliceFromByte({ source, byteIndex: declaration.location.byteIndex }),
	);
}

function fallbackDoc(name: string): JsDoc {
	return { doc: `Method form of {@linkcode mini.${name}}.`, tags: [] };
}

/**
 * Rewrites a mini JSDoc's examples for main: calls of every function that
 * became a method move to method form, and imports from mini move to the
 * main entrypoint (which no longer exports those functions).
 */
function mainExamples({
	jsDoc,
	module,
}: {
	jsDoc: JsDoc;
	module: Module;
}): JsDoc {
	const tags = jsDoc.tags.map((tag): JsDocTag => {
		if (tag.kind !== "example") return tag;

		let methodForm = tag.doc;
		for (const name of module.methodNames) {
			methodForm = toMethodForm({ code: methodForm, name }) ?? methodForm;
		}
		const doc = toMainImports({
			code: methodForm,
			entrypoint: module.feature.entrypoint,
			methods: module.methodNames,
			omitted: module.omitted,
		});

		return { ...tag, doc };
	});

	return { ...jsDoc, tags };
}

/** Rewrites a mini function's JSDoc for its method. */
function methodDoc({
	name,
	jsDoc,
	dropTemplates,
	module,
}: {
	name: string;
	jsDoc: JsDoc | undefined;
	dropTemplates: ReadonlySet<string>;
	module: Module;
}): JsDoc {
	const source = mainExamples({
		jsDoc: jsDoc ?? fallbackDoc(name),
		module,
	});
	const tags = source.tags.filter(
		(tag) =>
			!(tag.kind === "param" && tag.name === "self") &&
			!(tag.kind === "template" && dropTemplates.has(tag.name)),
	);

	return {
		doc: source.doc,
		tags: [...tags, { kind: "see", doc: `{@link mini.${name}}` }],
	};
}

interface MethodHead {
	readonly head: string;
	readonly body: string;
	readonly doc: string;
	readonly conversion: Conversion;
	readonly isPredicate: boolean;
}

/** The conversion context for rendering return types in `module`. */
function convertContextFor({
	module,
	context,
}: {
	module: Module;
	context: RenderContext;
}): ConvertContext {
	return {
		render: (type) => renderType({ type, context }),
		wrapTarget: (type) => wrapTargetOf(module.wrapNames, type),
		mappers: (target) => module.mappers.get(target) ?? [],
	};
}

/** The prefix that makes a member a generator when it re-yields lazily. */
function generatorStar(conversion: Conversion): string {
	return conversion.kind === "iterable" ? "*" : "";
}

/** Renders one signature of a `self`-first function as a method. */
function methodHead({
	module,
	name,
	signature: declared,
	classParams,
}: {
	module: Module;
	name: string;
	signature: FunctionDeclaration;
	classParams: readonly TypeParam[];
}): Generated<MethodHead> {
	const { feature } = module;
	const signature = labelled(module, declared);
	const [self, ...params] = signature.params;
	const selfType = self?.type;
	if (selfType?.kind !== "ref") {
		return failure({
			feature,
			symbol: name,
			message: "`self` must be typed as the primary class",
		});
	}
	if (selfType.args.length !== classParams.length) {
		return failure({
			feature,
			symbol: name,
			message: `\`self\` must pass all ${classParams.length} of ${feature.primary}'s type parameters`,
		});
	}

	const rename = new Map<string, string>();
	for (const [i, arg] of selfType.args.entries()) {
		const classParam = classParams[i];
		const isBareParam =
			arg.kind === "ref" &&
			arg.resolution.kind === "typeParam" &&
			arg.args.length === 0 &&
			signature.typeParams.some((tp) => tp.name === arg.name) &&
			!rename.has(arg.name);
		if (!isBareParam || arg.kind !== "ref" || classParam === undefined) {
			return failure({
				feature,
				symbol: name,
				message: `\`self\`'s type arguments must be distinct type parameters of ${name}`,
			});
		}
		rename.set(arg.name, classParam.name);
	}

	const classNames = new Set(classParams.map((tp) => tp.name));
	const ownParams = signature.typeParams.filter((tp) => !rename.has(tp.name));
	const curried = feature.uncurry?.includes(name) ?? false;
	const returnType = signature.returnType;
	if (returnType === undefined) {
		return failure({
			feature,
			symbol: name,
			message: "the return type must be annotated",
		});
	}
	if (curried && (returnType.kind !== "function" || params.length > 0)) {
		return failure({
			feature,
			symbol: name,
			message: "only `(self) => (…) => R` functions can be uncurried",
		});
	}

	const finalReturn =
		returnType.kind === "function" && curried
			? returnType.returnType
			: returnType;
	const methodParams =
		returnType.kind === "function" && curried ? returnType.params : params;
	const methodTypeParams =
		returnType.kind === "function" && curried
			? [...ownParams, ...returnType.typeParams]
			: ownParams;

	const clash = methodTypeParams.find((tp) => classNames.has(tp.name));
	if (clash !== undefined) {
		return failure({
			feature,
			symbol: name,
			message: `type parameter ${clash.name} shadows ${feature.primary}'s; rename it in mini`,
		});
	}

	const context = contextFor({
		module,
		fileUrl: signature.location.filename,
		rename,
	});
	const typeParams = renderTypeParams({
		typeParams: methodTypeParams,
		context,
		modifiers: modifiersOf(module, signature),
	});
	const paramList = methodParams
		.map((param) => renderParam({ param, context }))
		.join(", ");

	const outerArgs = ["this", ...params.map(forwardParam)].join(", ");
	const call = curried
		? `mini.${name}(${outerArgs})(${methodParams.map(forwardParam).join(", ")})`
		: `mini.${name}(${outerArgs})`;

	if (finalReturn.kind !== "predicate") {
		const converted = convertReturn({
			type: finalReturn,
			context: convertContextFor({ module, context }),
		});
		if (!converted.ok) {
			return failure({ feature, symbol: name, message: converted.error });
		}
		const { text, conversion } = converted.value;
		const isVoid =
			finalReturn.kind === "keyword" && finalReturn.keyword === "void";

		return ok({
			head: `${generatorStar(conversion)}${name}${typeParams}(${paramList}): ${text}`,
			body: convertedBody({ call, conversion, isVoid, indent: "\t\t" }),
			doc: renderMethodDoc({ module, name, signature, rename, context }),
			conversion,
			isPredicate: false,
		});
	}

	const subject = finalReturn.subject === "self" ? "this" : finalReturn.subject;
	const target =
		finalReturn.type === undefined
			? ""
			: ` is ${renderWrapped({ module, type: finalReturn.type, context })}`;
	const asserts = finalReturn.asserts ? "asserts " : "";

	return ok({
		head: `${name}${typeParams}(${paramList}): ${asserts}${subject}${target}`,
		body: finalReturn.asserts ? `${call};` : `return ${call};`,
		doc: renderMethodDoc({ module, name, signature, rename, context }),
		conversion: { kind: "none" },
		isPredicate: true,
	});
}

function renderMethodDoc({
	module,
	name,
	signature,
	rename,
	context,
}: {
	module: Module;
	name: string;
	signature: FunctionDeclaration;
	rename: ReadonlyMap<string, string>;
	context: RenderContext;
}): string {
	return renderJsDoc({
		jsDoc: methodDoc({
			name,
			jsDoc: signature.jsDoc,
			dropTemplates: new Set(rename.keys()),
			module,
		}),
		context,
		indent: "\t",
	});
}

/** The shared implementation of an overload set, forwarding every argument. */
function overloadImplementation({
	feature,
	name,
	heads,
	receiver,
}: {
	feature: Feature;
	name: string;
	heads: readonly { conversion: Conversion; isPredicate: boolean }[];
	receiver: "this" | undefined;
}): Generated<{ signature: string; body: string }> {
	const keys = new Set(heads.map((head) => conversionKey(head.conversion)));
	if (keys.size > 1) {
		return failure({
			feature,
			symbol: name,
			message: "overloads must agree on whether they return the primary type",
		});
	}
	if (heads.some((head) => head.isPredicate)) {
		return failure({
			feature,
			symbol: name,
			message: "overloaded type predicates are not supported",
		});
	}

	const args = receiver === undefined ? "args" : `[${receiver}, ...args]`;
	const call = `Reflect.apply(mini.${name}, undefined, ${args})`;
	const [first] = heads;
	const conversion = first?.conversion ?? { kind: "none" };
	if (conversion.kind !== "none" && conversion.kind !== "value") {
		return failure({
			feature,
			symbol: name,
			message: "overloads can only convert a plain return value",
		});
	}

	return ok({
		signature: `${name}(...args: unknown[]): unknown`,
		body: convertedBody({ call, conversion, isVoid: false, indent: "" }),
	});
}

function renderMethod({
	module,
	symbol,
	classParams,
}: {
	module: Module;
	symbol: DocSymbol;
	classParams: readonly TypeParam[];
}): Generated<Member> {
	const heads: MethodHead[] = [];
	for (const signature of signaturesOf(symbol)) {
		const head = methodHead({
			module,
			name: symbol.name,
			signature,
			classParams,
		});
		if (!head.ok) return head;
		heads.push(head.value);
	}

	const [only] = heads;
	if (heads.length === 1 && only !== undefined) {
		return ok({
			name: symbol.name,
			source: `${only.doc}\t${only.head} {\n\t\t${only.body}\n\t}\n`,
		});
	}

	const impl = overloadImplementation({
		feature: module.feature,
		name: symbol.name,
		heads,
		receiver: "this",
	});
	if (!impl.ok) return impl;

	const overloads = heads
		.map((head) => `${head.doc}\t${head.head};\n`)
		.join("");

	return ok({
		name: symbol.name,
		source: `${overloads}\t${impl.value.signature} {\n\t\t${impl.value.body}\n\t}\n`,
	});
}

/** Renders a non-`self` function whose return needs converting as a main wrapper. */
function renderWrapper({
	module,
	symbol,
}: {
	module: Module;
	symbol: DocSymbol;
}): Generated<Member> {
	const { feature } = module;
	const signatures = signaturesOf(symbol);
	const heads: {
		head: string;
		doc: string;
		conversion: Conversion;
		isPredicate: boolean;
	}[] = [];

	for (const declared of signatures) {
		const signature = labelled(module, declared);
		const context = contextFor({
			module,
			fileUrl: signature.location.filename,
			rename: EMPTY_RENAME,
		});
		const returnType = signature.returnType;
		if (returnType === undefined) {
			return failure({
				feature,
				symbol: symbol.name,
				message: "the return type must be annotated",
			});
		}

		const typeParams = renderTypeParams({
			typeParams: signature.typeParams,
			context,
			modifiers: modifiersOf(module, signature),
		});
		const params = signature.params
			.map((param) => renderParam({ param, context }))
			.join(", ");
		const doc = renderJsDoc({
			jsDoc: mainExamples({
				jsDoc: signature.jsDoc ?? {
					doc: `Main form of {@linkcode mini.${symbol.name}}.`,
					tags: [],
				},
				module,
			}),
			context,
		});

		const converted = convertReturn({
			type: returnType,
			context: convertContextFor({ module, context }),
		});
		if (!converted.ok) {
			return failure({
				feature,
				symbol: symbol.name,
				message: converted.error,
			});
		}
		const { text, conversion } = converted.value;

		heads.push({
			head: `export function${generatorStar(conversion)} ${symbol.name}${typeParams}(${params}): ${text}`,
			doc,
			conversion,
			isPredicate: false,
		});
	}

	const [only] = heads;
	const [onlySignature] = signatures;
	if (heads.length === 1 && only !== undefined && onlySignature !== undefined) {
		const args = onlySignature.params.map(forwardParam).join(", ");
		const body = convertedBody({
			call: `mini.${symbol.name}(${args})`,
			conversion: only.conversion,
			isVoid: false,
			indent: "\t",
		});

		return ok({
			name: symbol.name,
			source: `${only.doc}${only.head} {\n\t${body}\n}\n`,
		});
	}

	const impl = overloadImplementation({
		feature,
		name: symbol.name,
		heads,
		receiver: undefined,
	});
	if (!impl.ok) return impl;

	const overloads = heads.map((head) => `${head.doc}${head.head};\n`).join("");

	return ok({
		name: symbol.name,
		source: `${overloads}export function ${impl.value.signature} {\n\t${impl.value.body}\n}\n`,
	});
}

function renderClass({
	module,
	declaration,
	methods,
}: {
	module: Module;
	declaration: ClassDeclaration;
	methods: readonly Member[];
}): string {
	const { primary, construct } = module.feature;
	const context = contextFor({
		module,
		fileUrl: declaration.location.filename,
		rename: EMPTY_RENAME,
	});
	const modifiers = modifiersOf(module, declaration);
	const classTypeParams = renderTypeParams({
		typeParams: declaration.typeParams,
		context,
		modifiers,
	});
	const constOnly = new Map(
		[...modifiers].flatMap(([name, found]) =>
			found.includes("const") ? [[name, ["const"]]] : [],
		),
	);
	const staticTypeParams = renderTypeParams({
		typeParams: declaration.typeParams,
		context,
		modifiers: constOnly,
	});
	const args = declaration.typeParams.map((tp) => tp.name).join(", ");
	const applied = args === "" ? "" : `<${args}>`;

	const classDoc = renderJsDoc({
		jsDoc: {
			doc: [
				declaration.jsDoc?.doc.trim() ?? "",
				`This is the main, method-chaining \`${primary}\`: every \`self\`-first function of the mini API is a method, and methods whose mini form returns \`${primary}\` return this class. It extends the mini {@linkcode mini.${primary}}, so instances work with the mini functions too.`,
			]
				.filter((part) => part !== "")
				.join("\n\n"),
			tags: mainExamples({
				jsDoc: declaration.jsDoc ?? { doc: "", tags: [] },
				module,
			}).tags,
		},
		context,
	});
	const fromMiniDoc = renderJsDoc({
		jsDoc: {
			doc: `Views a mini {@linkcode mini.${primary}} as a main \`${primary}\`, returning it unchanged when it already is one. The view shares the mini instance's state, so a change through either is visible through both.`,
			tags: [
				{ kind: "param", name: "self", doc: `The ${primary} to convert` },
				{
					kind: "return",
					doc: `A main \`${primary}\` sharing \`self\`'s state`,
				},
			],
		},
		context,
		indent: "\t",
	});
	// An Enum's constructor takes the variant, not the struct params, so the
	// view is built from the variant and then rebound to the source's params.
	const rebuilt =
		construct === "variant"
			? `const params = getStructParams(self);\n\t\tconst view = new ${primary}${applied}(...params.variant);\n\t\tview[struct] = params;\n\n\t\treturn view;`
			: `return new ${primary}(getStructParams(self));`;
	const fromMini = `${fromMiniDoc}\tstatic fromMini${staticTypeParams}(self: mini.${primary}${applied}): ${primary}${applied} {\n\t\tif (self instanceof ${primary}) return self;\n\n\t\t${rebuilt}\n\t}\n`;

	const body = [fromMini, ...methods.map((method) => method.source)].join("\n");

	return `${classDoc}export class ${primary}${classTypeParams} extends mini.${primary}${applied} {\n${body}}\n`;
}

function renderModuleDoc(feature: Feature, miniSpecifier: string): string {
	const lines = [
		`Main entrypoint for \`${feature.entrypoint}\`: the method-chaining API.`,
		"",
		`\`${feature.primary}\` here extends the mini \`${feature.primary}\` from \`${feature.entrypoint}/mini\`, so its instances work with every mini function too. Each \`self\`-first mini function is a method, and functions whose mini form returns \`${feature.primary}\` return this main class, so calls chain.`,
		"",
		`Generated from \`${miniSpecifier}\` by \`deno task gen:main\`; edit the mini source, then regenerate.`,
	];
	if (feature.example !== undefined) {
		lines.push("", "@example", "```ts", ...feature.example.split("\n"), "```");
	}
	lines.push("", "@module");

	const body = lines
		.map((line) => (line === "" ? " *" : ` * ${line}`))
		.join("\n");

	return `/**\n${body}\n */\n`;
}

function renderImports({
	module,
	miniSpecifier,
}: {
	module: Module;
	miniSpecifier: string;
}): string {
	const lines = [
		module.feature.construct === "variant"
			? 'import { getStructParams, struct } from "@sekhmet/primordials/struct";'
			: 'import { getStructParams } from "@sekhmet/primordials/struct";',
		`import * as mini from "${miniSpecifier}";`,
		...(module.feature.wraps ?? []).map(
			(target) => `import { ${target.type} } from "${target.from}";`,
		),
		...[...module.typeImports].map(([specifier, names]) => {
			const list = [...names]
				.map(([name, local]) => (name === local ? name : `${name} as ${local}`))
				.sort()
				.join(", ");
			return `import type { ${list} } from "${specifier}";`;
		}),
	];

	return `${lines.join("\n")}\n`;
}

function renderReExports({
	values,
	types,
	miniSpecifier,
}: {
	values: readonly string[];
	types: readonly string[];
	miniSpecifier: string;
}): string {
	const lines: string[] = [];
	if (types.length > 0) {
		lines.push(
			`export type { ${[...types].sort().join(", ")} } from "${miniSpecifier}";`,
		);
	}
	if (values.length > 0) {
		lines.push(
			`export { ${[...values].sort().join(", ")} } from "${miniSpecifier}";`,
		);
	}

	return lines.length === 0 ? "" : `${lines.join("\n")}\n`;
}

/**
 * Generates a feature's main module from its mini barrel's symbols. The
 * output is valid TypeScript but not yet Biome-formatted.
 *
 * @param input - The feature, its mini symbols and their sources
 * @returns The module source, or why it could not be generated
 */
export function generateMain(input: GenerateInput): Generated<string> {
	const { feature, symbols, sources, miniUrl, outputUrl } = input;
	const omitted = new Set(feature.omit ?? []);

	const primarySymbol = symbols.find(
		(symbol) => symbol.name === feature.primary,
	);
	const declaration = primarySymbol?.declarations.find(
		(decl): decl is ClassDeclaration => decl.kind === "class",
	);
	if (declaration === undefined) {
		return failure({
			feature,
			symbol: feature.primary,
			message: "the mini barrel must export the primary class",
		});
	}

	const wrapNames = new Set([
		feature.primary,
		...(feature.wraps ?? []).map((t) => t.type),
	]);
	const miniNames = new Set(symbols.map((symbol) => symbol.name));
	const mappers = new Map<string, readonly (string | undefined)[]>([
		[feature.primary, feature.mappers ?? []],
		...(feature.wraps ?? []).map(
			(target) => [target.type, target.mappers ?? []] as const,
		),
	]);

	const methodSymbols: DocSymbol[] = [];
	const wrapperSymbols: DocSymbol[] = [];
	const values: string[] = [];
	const types: string[] = [];

	for (const symbol of symbols) {
		if (symbol.name === feature.primary || omitted.has(symbol.name)) continue;

		const signatures = signaturesOf(symbol);
		if (signatures.length > 0) {
			const selfFirst = signatures.map((sig) =>
				isSelfOfPrimary(feature.primary, sig.params[0]),
			);
			if (selfFirst.every(Boolean)) {
				methodSymbols.push(symbol);
				continue;
			}
			if (selfFirst.some(Boolean)) {
				return failure({
					feature,
					symbol: symbol.name,
					message: "overloads must all or none take `self` first",
				});
			}
			const returnsWrapped = signatures.map((sig) =>
				needsConversion({ wrapNames, type: sig.returnType }),
			);
			if (returnsWrapped.some(Boolean)) {
				wrapperSymbols.push(symbol);
				continue;
			}
		}

		const typeOnly = symbol.declarations.every(
			(decl) => decl.kind === "other" && decl.typeOnly,
		);
		(typeOnly ? types : values).push(symbol.name);
	}

	const module: Module = {
		feature,
		miniNames,
		methodNames: new Set(methodSymbols.map((symbol) => symbol.name)),
		omitted,
		wrapNames,
		mappers,
		sources,
		outputUrl,
		typeImports: new Map(),
		localNames: new Set([
			"mini",
			"getStructParams",
			"struct",
			...wrapNames,
			...wrapperSymbols.map((symbol) => symbol.name),
		]),
	};

	const methods: Member[] = [];
	for (const symbol of methodSymbols) {
		const method = renderMethod({
			module,
			symbol,
			classParams: declaration.typeParams,
		});
		if (!method.ok) return method;
		methods.push(method.value);
	}

	const wrappers: Member[] = [];
	for (const symbol of wrapperSymbols) {
		const wrapper = renderWrapper({ module, symbol });
		if (!wrapper.ok) return wrapper;
		wrappers.push(wrapper.value);
	}

	const classSource = renderClass({ module, declaration, methods });
	const miniSpecifier = specifierFor({ from: outputUrl, to: miniUrl });

	const parts = [
		`${GENERATED_HEADER}\n`,
		renderModuleDoc(feature, miniSpecifier),
		renderImports({ module, miniSpecifier }),
		renderReExports({ values, types, miniSpecifier }),
		classSource,
		...wrappers.map((wrapper) => wrapper.source),
	].filter((part) => part !== "");

	const source = parts.join("\n");

	// Main modules that convert to each other's classes import each other, so
	// a wrap target may only be used once the cycle has finished evaluating.
	const uses = moduleScopeValueUses({
		source,
		names: (feature.wraps ?? []).map((target) => target.type),
	});
	if (uses.length > 0) {
		return failure({
			feature,
			symbol: undefined,
			message: `wrap targets are used at module scope, which the main import cycle can't allow: ${uses.join(", ")}`,
		});
	}

	return ok(source);
}
