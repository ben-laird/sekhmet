/**
 * Renders the probe's entry module: the table of export paths to import, as
 * literal `import()` calls a bundler can follow, and the hand-off of the
 * report to whatever runs the probe on the target.
 *
 * @module
 */

import type { ExportPath } from "@/src/package.ts";
import type { Target } from "@/src/runtime.ts";

/** Where the browser entry leaves the report for the Playwright runner. */
export const BROWSER_REPORT_GLOBAL = "__compatSmokeReport";

/** The entry module's file name, next to the copied probe. */
export const ENTRY_FILE = "entry.ts";

function renderLoad({ package: pkg, specifier }: ExportPath): string {
	const literal = JSON.stringify(specifier);
	return `\t{ package: ${JSON.stringify(pkg)}, specifier: ${literal}, load: () => import(${literal}) },`;
}

function renderHandOff(target: Target): string[] {
	switch (target.kind) {
		case "server":
			return [
				"const report = await runProbe({ loads: LOADS, exercises: EXERCISES });",
				"console.log(REPORT_MARKER + JSON.stringify(report));",
			];
		case "browser":
			return [
				"const report = await runProbe({ loads: LOADS, exercises: EXERCISES });",
				`Reflect.set(globalThis, ${JSON.stringify(BROWSER_REPORT_GLOBAL)}, report);`,
			];
		case "workerd":
			// A Worker's module contract is its default export.
			return [
				"export default {",
				"\tasync fetch(): Promise<Response> {",
				"\t\tconst report = await runProbe({ loads: LOADS, exercises: EXERCISES });",
				"\t\treturn new Response(REPORT_MARKER + JSON.stringify(report));",
				"\t},",
				"};",
			];
	}
}

/**
 * Renders the entry module for a target.
 *
 * @param params - The target and every export path to import
 * @returns The module's TypeScript source
 */
export function renderEntry({
	target,
	paths,
}: {
	target: Target;
	paths: readonly ExportPath[];
}): string {
	return [
		"// Generated by @sekhmet/compat-smoke for one run; not checked in.",
		'import { EXERCISES } from "./exercises/mod.ts";',
		'import { type Load, REPORT_MARKER, runProbe } from "./probe.ts";',
		"",
		"const LOADS: Load[] = [",
		...paths.map(renderLoad),
		"];",
		"",
		...renderHandOff(target),
		"",
	].join("\n");
}
